#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Trigger Out 선을 세우고 내리는 **공통 알맹이** (ICS·ICG 가 함께 쓴다).

두 계통이 같은 동작을 하는데 **쉬는 상태만 다르다**:

| | `TRIGOUTLEVEL` | `TRIGOUTFORCE` | 뜻 |
|---|---|---|---|
| **guide** (`REST_GUIDE`) | `0` | **`1`** | 선을 **우리가 붙들어** LOW 로 고정.  guide 는 셔터가 없다 |
| **science** (`REST_SCIENCE`) | `0` | **`0`** | 선을 **타이밍 스크립트에 돌려준다** -- 그것이 셔터 노출의 정상 모드다 (매뉴얼 p.15) |

⛔ **여기에 모아 둔 이유**: 순서와 적용 횟수가 미묘한데 두 벌로 두면 갈린다.
`SHOPEN`/`TRIGOUT` 은 **에지 시점**이 뜻이라 순서가 곧 규범이다.

**규범** (운영자 확정 2026-09-09):

| | 올림 | 내림 |
|---|---|---|
| | 올림 (`raise_line`) | 내림 (`rest_line`) -- 시한 만료·명시적 둘 다 |
|---|---|---|
| **guide** | `LEVEL=1`+`FORCE=1` | `LEVEL=0`+**`FORCE=1`** (계속 우리 손) |
| **science** | `LEVEL=1`+`FORCE=1` | `LEVEL=0`+**`FORCE=0`** (스크립트에 반환) |

⭐ **둘 다 `APPLYSYSTEM` 한 번**이다 (운영자 확정 2026-09-09).  올림은 두 계통이
**완전히 같고**, 내림은 돌아갈 쉬는 `FORCE` 만 다르다.
⚠️ **science 에서 적분 중이면** 내림이 선을 스크립트에 돌려줄 뿐이라 셔터는
**노출시간 완료 시점(`NoIntMS`)에** 닫힌다 -- 타이머 만료든 `SHCLOSE` 든 같다.
그래서 **적분 중에는 `SHOPEN <초>` 의 `<초>` 가 사실상 뜻이 없다**.

⭐ **어느 쪽도 적용은 한 번이다** (guide 가 무장이 풀린 예외뿐).
⛔ **science 는 노출을 방해하지 않는 것이 우선**이다 (운영자 확정 2026-09-09):
무장(`LEVEL=0`+`FORCE=1`)을 앞세우면 그 한 적용 동안 핀이 강제 LOW 라 **노출 중
셔터가 잠깐 닫힌다**.  그래서 둘을 같이 세운다 -- 이미 열려 있었다면 **그대로**다.
⚠️ 대가는 **에지를 보장하지 않는 것**이고, `SHCLOSE` 도 적분 중이면 **안 닫힌다**
(선을 스크립트에 돌려줄 뿐).  둘 다 의도한 것이다 -- `README.md` 참조.

⭐ **에지는 마지막 한 쓰기가 만든다.**  무장(`LEVEL=0` + 쉬는 `FORCE`)을 앞세우면
앞 상태와 무관하게 `LEVEL=1` 한 번이 상승 에지다.  종전 판(`LEVEL=1` -> `FORCE=1`)
은 앞 상태에 따라 에지가 첫 명령이기도 둘째이기도 해서 시점을 못 짚었다
(운영자 2026-09-08).

⭐ **무장은 한 번의 `APPLYSYSTEM`** 으로 둘을 같이 세운다 (`ctrl.set_trigger`) --
따로 적용하면 그 사이에 *"강제는 걸렸는데 레벨은 옛 값"* 인 찰나가 생긴다.

⏳ **취득 중 `APPLYSYSTEM` 의 안전성은 창마다 다르고 둘이 미확인이다**
(DevNote 11.50):

| 창 | 상태 |
|---|---|
| 유휴 | ✅ 늘 하고 있다 |
| 적분 **개시 직전** | ✅ science 정상 경로가 매 노출 그렇게 돈다 |
| **적분 중** | ⏳ 미확인 -- ⛔ `ArchonBackend.close_shutter()` 가 실제로 여기서 보낸다 |
| **독출 중** | ⏳ 미확인 -- science 는 일부러 피한다 |
"""

from __future__ import annotations

import logging

#: `(TRIGOUTLEVEL, TRIGOUTFORCE)` -- `ctrl.trigger_state()` 가 주는 것과 같은 꼴.
REST_GUIDE = ('0', '1')
REST_SCIENCE = ('0', '0')

log = logging.getLogger('ics_archon.trigout')


async def raise_line(ctrl) -> None:  # noqa: ANN001
    """선을 HIGH 로 -- `LEVEL=1`+`FORCE=1` **한 적용**.  두 계통이 같다.

    ⭐ **노출을 방해하지 않는 것이 우선**이다 (운영자 확정 2026-09-09).  무장
    (`LEVEL=0`+`FORCE=1`)을 앞세우면 그 한 적용 동안 핀이 **강제 LOW** 라
    science 에서는 **노출 중 셔터가 잠깐 닫힌다**.  둘을 같이 세우면 이미 열려
    있던 선은 **그대로**다.
    ⚠️ 대가: **에지를 보장하지 않는다** -- 이미 HIGH 였다면 에지가 없다.
    ⭐ **건너뛰기 판단이 없다** -- 늘 쓰므로 `RCONFIG` 되읽기도, *"캐시가
    거짓이면 조용히 아무것도 안 한다"* 는 결함 부류도 사라진다.
    """
    await ctrl.set_trigger(high=True, forced=True)


async def rest_line(ctrl, rest: tuple) -> None:  # noqa: ANN001
    """선을 내려 **쉬는 상태로** -- 한 적용.  시한 만료와 명시적 내림이 같다.

    `LEVEL=0` + 그 계통의 쉬는 `FORCE` 를 같이 쓴다.  ⭐ **여기서만 두 계통이
    갈린다.**

    * **guide**(`FORCE=1`): 선이 계속 우리 것이라 시한 만료와 같은 값이다.
    * **science**(`FORCE=0`): 선을 **타이밍 스크립트에 돌려준다**.
      ⚠️ **적분 중이면 셔터가 그 자리에서 닫히지 않는다** -- 스크립트가 몰기
      시작하므로 **노출 종료 시점(`NoIntMS`)에** 닫힌다 (운영자 2026-09-09).
      ⭐ **타이머 만료도 같다** (운영자 확정 2026-09-09) -- 둘 다 넘겨주므로
      적분 중이라면 `<초>` 가 지나도 셔터는 안 닫히고 노출이 제 시간에 닫는다.
      ⚠️ 그래서 **적분 중에는 `SHOPEN <초>` 의 `<초>` 가 사실상 뜻이 없다** --
      `<초>` 가 뜻을 갖는 것은 스크립트가 노출을 안 돌릴 때(교정·점검)다.
      ⛔ **조기 차단은 또 다른 명령이다**: `STOP`/`ABORT` 의
      `ArchonBackend.close_shutter()` 가 `FORCE=1`+`LEVEL=0` 으로 붙들어 끊는다.
    """
    await ctrl.set_trigger(high=False, forced=rest[1] == '1')
